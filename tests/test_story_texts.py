LANGUAGE_NAMES = {"ru": "Russian", "en": "English", "pl": "Polish"}


@pytest.mark.parametrize("language", config.LANGUAGES)
def test_every_language_has_the_same_template(language: str) -> None:
    text = digest.template(story_texts.TEMPLATE, language)
    reference = digest.template(story_texts.TEMPLATE, "ru")
    assert text.count(digest.FACTS_MARKER) == 1
    assert f"1. Write every text in {LANGUAGE_NAMES[language]}." in text
    assert text.replace(LANGUAGE_NAMES[language], "<L>") == reference.replace("Russian", "<L>")
    for other, name in LANGUAGE_NAMES.items():
        if other != language:
            assert name not in text


