def test_missing_texts_are_generated_once_and_cached(store: StoryStore) -> None:
    story = make_story(store)
    updates = store.timeline(story.id)[1:]
    model = FakeModel()

    local, error = story_texts.localize(store, story, updates, "en", model, NOW)

    assert error is None
    assert (local.title, local.summary, local.language) == (
        "Story in English?",
        "Synthetic: rumoured summary.",
        "en",
    )
    assert local.what_changed == {u.id: f"Synthetic: change {u.id}." for u in updates}
    assert local.update_languages == {u.id: "en" for u in updates}
    assert len(model.prompts) == 1

    again, error = story_texts.localize(store, story, updates, "en", model, NOW)
    assert error is None
    assert again == local
    assert len(model.prompts) == 1  # all cached: no second call


def test_the_model_gets_only_the_story_and_the_updates_asked_for(store: StoryStore) -> None:
    story = make_story(store)
    other = make_story(store, 2)
    first, second, third = store.timeline(story.id)
    model = FakeModel()

    story_texts.localize(store, story, [third], "pl", model, NOW)
    document = model.document()

    assert document == {
        "story": {
            "language": "ru",
            "title": story.title,
            "summary": story.summary,
            # where the story came from: its first sourced update
            "source": {
                "id": first.id,
                "language": "ru",
                "headline": first.update.headline,
                "source": first.update.source,
                "url": first.update.url,
                "published": first.update.published_at.isoformat(),
                "what_changed": first.update.what_changed,
            },
        },
        "updates": [
            {
                "id": third.id,
                "language": "ru",
                "headline": third.update.headline,
                "source": third.update.source,
                "url": third.update.url,
                "published": third.update.published_at.isoformat(),
                "what_changed": third.update.what_changed,
            }
        ],
    }
    prompt = model.prompts[0]
    assert second.update.url not in prompt
    assert other.title not in prompt
    assert prompt.startswith(digest.template(story_texts.TEMPLATE, "pl").split(FACTS_BLOCK)[0])
    assert "in Polish" in prompt


