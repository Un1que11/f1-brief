def test_a_state_file_from_f26_keeps_its_russian_texts(state: Path) -> None:
    with sqlite3.connect(state) as db:
        db.execute(
            "CREATE TABLE schema_versions (component TEXT NOT NULL PRIMARY KEY, "
            "version INTEGER NOT NULL)"
        )
        for step in _MIGRATIONS[:4]:
            for statement in step:
                db.execute(statement)
        db.execute("INSERT INTO schema_versions VALUES ('stories', 4)")
        db.execute(
            "INSERT INTO stories (slug, title_ru, summary_ru, status, created_at, "
            "last_update_at) VALUES ('kept', 'Заголовок', 'Описание', 'rumor', ?, ?)",
            (NOW.isoformat(), NOW.isoformat()),
        )
        db.execute(
            "INSERT INTO story_updates (story_id, headline, url, source, what_changed_ru, "
            "recorded_at, status) VALUES (1, 'h', 'https://example.com/kept', 'Outlet', "
            "'Что изменилось', ?, 'rumor')",
            (NOW.isoformat(),),
        )
    with StoryStore(state) as store:
        story = store.get(1)
        assert story is not None
        assert (story.title, story.summary, story.language) == ("Заголовок", "Описание", "ru")
        [kept] = store.timeline(1)
        assert kept.update.what_changed == "Что изменилось"
        assert kept.update.language == "ru"
        assert kept.update.url == "https://example.com/kept"
        assert store.story_text(1, "en") is None
        # The migrated rows work like new ones: a text can be cached for them.
        store.cache_texts(1, "en", StoryText("Title", "Summary"), {kept.id: "Changed"}, NOW)
        assert store.story_text(1, "en") == StoryText("Title", "Summary")
    with sqlite3.connect(state) as db:
        assert db.execute("SELECT version FROM schema_versions").fetchall() == [(SCHEMA_VERSION,)]
        columns = {row[1] for row in db.execute("PRAGMA table_info(stories)")}
        assert {"title", "summary", "language"} <= columns
        assert not {"title_ru", "summary_ru"} & columns


# --- the cache ------------------------------------------------------------------------------


def test_the_stored_language_needs_no_cache(store: StoryStore) -> None:
    story = make_story(store)
    first = store.timeline(story.id)[0]
    assert store.story_text(story.id, "ru") == StoryText(story.title, story.summary)
    assert store.update_text(first.id, "ru") == first.update.what_changed
    assert store.story_text(story.id, "en") is None
    assert store.update_text(first.id, "en") is None


def test_cached_texts_come_back_per_language(store: StoryStore) -> None:
    story = make_story(store)
    first, second, _ = store.timeline(story.id)
    store.cache_texts(story.id, "en", StoryText("T en", "S en"), {first.id: "W en"}, NOW)
    store.cache_texts(story.id, "pl", None, {second.id: "W pl"}, NOW)

    assert store.story_text(story.id, "en") == StoryText("T en", "S en")
    assert store.story_text(story.id, "pl") is None
    assert store.update_text(first.id, "en") == "W en"
    assert store.update_text(second.id, "en") is None
    assert store.update_text(second.id, "pl") == "W pl"
    # The stored texts are untouched.
    assert store.get(story.id) == story
    assert store.timeline(story.id)[0] == first


def test_the_cache_refuses_what_does_not_fit_and_stores_nothing(store: StoryStore) -> None:
    story = make_story(store)
    other = make_story(store, 2)
    [first, *_] = store.timeline(story.id)
    [foreign, *_] = store.timeline(other.id)
    text = StoryText("T", "S")

    with pytest.raises(StoryError, match="written in ru"):
        store.cache_texts(story.id, "ru", text, {}, NOW)
    with pytest.raises(StoryError, match="written in ru"):
        store.cache_texts(story.id, "ru", None, {first.id: "W"}, NOW)
    with pytest.raises(StoryError, match="no update"):
        store.cache_texts(story.id, "en", text, {foreign.id: "W"}, NOW)
    with pytest.raises(ValueError, match="what_changed"):
        store.cache_texts(story.id, "en", text, {first.id: " "}, NOW)
    with pytest.raises(ValueError, match="title"):
        store.cache_texts(story.id, "en", StoryText("", "S"), {}, NOW)
    with pytest.raises(StoryError, match="no story"):
        store.cache_texts(99, "en", text, {}, NOW)

    assert store.story_text(story.id, "en") is None
    assert store.update_text(first.id, "en") is None


