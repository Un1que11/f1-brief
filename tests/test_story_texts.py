def test_the_digest_facts_carry_the_texts_and_their_language(store: StoryStore) -> None:
    story = make_story(store)
    store.follow(story.id, NOW - timedelta(days=3))
    model = FakeModel()

    def texts(s: Story, updates: list[StoryUpdate]) -> story_texts.Localized:
        local, error = story_texts.localize(store, s, updates, "en", model, NOW)
        assert error is None
        return local

    data = facts.stories_facts(store, NOW - timedelta(days=3), True, DEFAULT_FAVOURITES, texts)
    [entry] = data["followed"]
    assert (entry["title"], entry["language"]) == ("Story in English?", "en")
    updates = store.timeline(story.id)[1:]
    assert [(u["what_changed"], u["language"], u["link"]) for u in entry["updates_since"]] == [
        (f"Synthetic: change {u.id}.", "en", u.update.url) for u in updates
    ]
    # The sources are the stored ones, never generated.
    assert data["sources"] == [{"name": u.update.source, "url": u.update.url} for u in updates]


