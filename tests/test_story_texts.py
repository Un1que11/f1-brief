def broken(prompt: str) -> str:
    raise GenerationError("claude exited with 1")


@pytest.mark.parametrize(
    ("model", "reason"),
    [
        (broken, "exited with 1"),
        (FakeModel("not json"), "not JSON"),
        (FakeModel(["a list"]), "not a JSON object"),
        (FakeModel({"summary": "S", "updates": []}), "title is missing"),
        (FakeModel({"title": "T", "summary": "S", "updates": {}}), "not a list"),
        (FakeModel({"title": "T", "summary": "S", "updates": [{"id": "1"}]}), "integer id"),
        (FakeModel({"title": "T", "summary": "S", "updates": []}), "no text for updates"),
    ],
)
def test_a_failed_generation_caches_nothing_and_says_why(
    store: StoryStore, model: Any, reason: str
) -> None:
    story = make_story(store)
    updates = store.timeline(story.id)[1:]

    local, error = story_texts.localize(store, story, updates, "en", model, NOW)

    assert error is not None
    assert reason in error
    assert local.language == "ru"
    assert local.what_changed == {u.id: u.update.what_changed for u in updates}
    assert store.story_text(story.id, "en") is None
    assert all(store.update_text(u.id, "en") is None for u in updates)


def test_an_answer_with_texts_not_asked_for_is_refused(store: StoryStore) -> None:
    story = make_story(store)
    first, second, _third = store.timeline(story.id)
    asked = [{"id": second.id, "what_changed": "W"}]
    extra = {"id": first.id, "what_changed": "X"}
    for updates in ([*asked, extra], asked + asked):
        answer = {"title": "T", "summary": "S", "updates": updates}
        _local, error = story_texts.localize(store, story, [second], "en", FakeModel(answer), NOW)
        assert error is not None
        assert re.search("not asked for|twice", error)
        assert store.update_text(second.id, "en") is None


def test_a_fenced_answer_is_read() -> None:
    answer = '```json\n{"updates": [{"id": 3, "what_changed": " W "}]}\n```'
    assert story_texts.parse_answer(answer, False, [3]) == (None, {3: "W"})


