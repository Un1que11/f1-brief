NOW = datetime(2026, 10, 21, 8, tzinfo=UTC)
FACTS_BLOCK = "<facts>\n"


def update(n: int, language: str = "ru") -> Update:
    return Update(
        headline=f"Synthetic headline {n}",
        url=f"https://example.com/story-{n}",
        source=f"Outlet {n}",
        what_changed=f"Синтетика: изменение {n}.",
        published_at=NOW - timedelta(days=20) + timedelta(hours=n),
        language=language,
    )


@pytest.fixture
def state(tmp_path: Path) -> Path:
    return tmp_path / "state.db"


@pytest.fixture
def store(state: Path) -> Iterator[StoryStore]:
    with StoryStore(state) as opened:
        yield opened


def make_story(store: StoryStore, n: int = 1) -> Story:
    story = store.create(
        f"story-{n}",
        f"Сюжет {n}?",
        f"Синтетика: по слухам, описание {n}.",
        StoryStatus.RUMOR,
        [Entity(EntityKind.DRIVER, "bearman")],
        update(10 * n),
        NOW - timedelta(days=5),
        language="ru",
    )
    store.add_update(story.id, update(10 * n + 1), NOW - timedelta(days=2))
    store.add_update(story.id, update(10 * n + 2), NOW - timedelta(days=1))
    stored = store.get(story.id)
    assert stored is not None
    return stored


class FakeModel:
    """Answers like the template asks: English texts for whatever the document holds."""

    def __init__(self, answer: Any = None) -> None:
        self.prompts: list[str] = []
        self.answer = answer

    def document(self, index: int = -1) -> dict[str, Any]:
        prompt = self.prompts[index]
        return json.loads(prompt.split(FACTS_BLOCK, 1)[1].split("\n</facts>", 1)[0])

    def __call__(self, prompt: str) -> str:
        self.prompts.append(prompt)
        if self.answer is not None:
            return self.answer if isinstance(self.answer, str) else json.dumps(self.answer)
        document = self.document()
        answer: dict[str, Any] = {
            "updates": [
                {"id": u["id"], "what_changed": f"Synthetic: change {u['id']}."}
                for u in document["updates"]
            ]
        }
        if "story" in document:
            answer |= {"title": "Story in English?", "summary": "Synthetic: rumoured summary."}
        return json.dumps(answer)


