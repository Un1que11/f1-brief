def test_the_digest_command_generates_and_caches_the_missing_texts(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str], english: Path
) -> None:
    model = FakeModel()
    monkeypatch.setattr(story_texts, "default_model", lambda name=None: model)
    written: list[dict[str, Any]] = []

    def fake_generate(document: dict[str, Any], _model: object, language: str) -> str:
        assert language == "en"
        written.append(document)
        return "Digest."

    monkeypatch.setattr(digest, "generate", fake_generate)

    assert main(["digest", "--state", str(english)]) == 0
    [entry] = written[0]["sections"]["stories"]["followed"]
    assert (entry["title"], entry["language"]) == ("Story in English?", "en")
    assert len(model.prompts) == 1

    # `facts` and `--prompt-only` never run claude: they read the cache.
    monkeypatch.setattr(story_texts, "default_model", lambda name=None: broken)
    capsys.readouterr()
    assert main(["facts", "--state", str(english)]) == 0
    [cached] = json.loads(capsys.readouterr().out)["sections"]["stories"]["followed"]
    assert cached == entry


